"""PDF artifacts: work tickets, receipts, pre-check briefs. Bilingual headings."""
from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from .execution import GENERATED


def _doc(path: Path, title: str, subtitle: str, rows: list[tuple[str, str]], notes: list[str], footer: str) -> Path:
    ss = getSampleStyleSheet()
    story = [Paragraph(f"<b>{title}</b>", ss["Title"]), Paragraph(subtitle, ss["Normal"]), Spacer(1, 6 * mm)]
    t = Table([[Paragraph(f"<b>{k}</b>", ss["Normal"]), Paragraph(str(v), ss["Normal"])] for k, v in rows],
              colWidths=[55 * mm, 115 * mm])
    t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.4, colors.grey), ("VALIGN", (0, 0), (-1, -1), "TOP"),
                           ("BACKGROUND", (0, 0), (0, -1), colors.whitesmoke)]))
    story += [t, Spacer(1, 6 * mm)]
    for n in notes:
        story += [Paragraph(n, ss["Normal"]), Spacer(1, 2 * mm)]
    story += [Spacer(1, 8 * mm), Paragraph(f"<font size=8 color=grey>{footer}</font>", ss["Normal"])]
    SimpleDocTemplate(str(path), pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm).build(story)
    return path


def work_ticket(ticket_id: str, case_id: str, rows: list[tuple[str, str]], citations: list[str]) -> Path:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    notes = ["<b>Policy basis / Asas polisi</b>"] + [f"• {c}" for c in citations]
    return _doc(GENERATED / f"{ticket_id}.pdf", f"Work Ticket / Tiket Kerja {ticket_id}",
                f"MyTadbir · Case / Kes {case_id} · Generated / Dijana {now}", rows, notes,
                "Generated by MyTadbir (demo). Contractor and council APIs are simulated for the competition demo.")


def receipt(receipt_no: str, case_id: str, rows: list[tuple[str, str]]) -> Path:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    return _doc(GENERATED / f"{receipt_no}.pdf", f"Receipt / Resit {receipt_no}",
                f"MyTadbir · Case / Kes {case_id} · {now}", rows, [],
                "Demo receipt. No real payment was made; the JPJ payment API is simulated.")
